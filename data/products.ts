type Draft = {
  id: string;
  sku: string;
  slug: string;
  title: string;
  subtitle: string;
  category: ProductCategory;
  playStyles: PlayStyle[];
  collections: string[];
  price: number;
  shortDescription: string;
  fullDescription: string;
  playDescription: string;
  ageMinimum: number;
  ageMaximum: number | null;
  adultSupervisionRequired?: boolean;
  warningText?: string | null;
  warningRequired?: boolean;
  chokingHazard?: boolean;
  smallParts?: boolean;
  magnetsIncluded?: boolean;
  batteryIncluded?: boolean;
  batteryType?: string | null;
  batteryCount?: number;
  material: string;
  fillingMaterial?: string | null;
  paintOrCoating?: string | null;
  dimensions: { lengthIn: number; widthIn: number; heightIn: number };
  weightLbs: number;
  pieceCount: number | null;
  packageContents: string[];
  assemblyRequired?: boolean;
  instructionsIncluded?: boolean;
  careInstructions: string;
  safetyInstructions: string;
  colors?: { name: string; hex: string }[];
  featured?: boolean;
  newArrival?: boolean;
  relatedProductIds: string[];
  keyDetail: string;
  heightDisplay?: string | null;
  playerCount?: string | null;
  playTimeMinutes?: string | null;
  readingRequired?: boolean;
  indoorOutdoor?: "indoor" | "outdoor" | "both";
  secondaryCategories?: string[];
};

function buildProduct(draft: Draft): Product {
  const incompleteReasons = [
    "Manufacturer and supplier SKU must be mapped to a verified source product.",
    "Age grade, warnings, materials, and compliance documents require owner verification before launch.",
  ];

  if (draft.magnetsIncluded) {
    incompleteReasons.push("Magnet construction and third-party test documentation must be verified before sale.");
  }

  return {
    id: draft.id,
    sku: draft.sku,
    supplierSku: `PENDING-${draft.sku}`,
    upc: null,
    slug: draft.slug,
    brand: "Sunny Bunny Toy Co.",
    manufacturer: "Pending verification",
    importer: "Sunny Bunny Toys LLC",
    title: draft.title,
    subtitle: draft.subtitle,
    category: draft.category,
    secondaryCategories: draft.secondaryCategories ?? [],
    collections: draft.collections,
    playStyles: draft.playStyles,
    price: draft.price,
    compareAtPrice: null,
    currency: "USD",
    shortDescription: draft.shortDescription,
    fullDescription: draft.fullDescription,
    playDescription: draft.playDescription,
    ageMinimum: draft.ageMinimum,
    ageMaximum: draft.ageMaximum,
    ageGradeSource: "Pending manufacturer label verification",
    ageGradeVerified: false,
    ageGradeVerifiedAt: null,
    adultSupervisionRequired: draft.adultSupervisionRequired ?? false,
    warningText: draft.warningText ?? null,
    warningRequired: draft.warningRequired ?? Boolean(draft.warningText),
    chokingHazard: draft.chokingHazard ?? false,
    smallParts: draft.smallParts ?? false,
    magnetsIncluded: draft.magnetsIncluded ?? false,
    batteryIncluded: draft.batteryIncluded ?? false,
    batteryType: draft.batteryType ?? null,
    batteryCount: draft.batteryCount ?? 0,
    material: draft.material,
    fillingMaterial: draft.fillingMaterial ?? null,
    paintOrCoating: draft.paintOrCoating ?? null,
    dimensions: { ...draft.dimensions, unit: "in" },
    weightLbs: draft.weightLbs,
    pieceCount: draft.pieceCount,
    packageContents: draft.packageContents,
    assemblyRequired: draft.assemblyRequired ?? false,
    instructionsIncluded: draft.instructionsIncluded ?? true,
    careInstructions: draft.careInstructions,
    safetyInstructions: draft.safetyInstructions,
    images: [
      {
        src: `/products/${draft.slug}/main.png`,
        alt: `${draft.title} on a white background`,
        type: "main",
      },
    ],
    imageSource: "commissioned",
    imageLicense:
      "Studio-style presentation photography matching the merchandising title. Replace with manufacturer-authorized media before production launch.",
    availableColors: draft.colors ?? [],
    availableVariants:
      draft.colors?.map((c, i) => ({
        id: `${draft.id}-color-${i}`,
        label: c.name,
        colorHex: c.hex,
        available: true,
      })) ?? [],
    stockStatus: "in_stock",
    maximumOrderQuantity: 10,
    shippingWeight: draft.weightLbs,
    featured: draft.featured ?? false,
    newArrival: draft.newArrival ?? false,
    giftEligible: true,
    underTwentyFive: draft.price < 25,
    underFifty: draft.price < 50,
    relatedProductIds: draft.relatedProductIds,
    complianceVerified: false,
    cpcRequired: true,
    cpcDocumentReference: null,
    testReportReference: null,
    trackingLabelCode: null,
    active: true,
    incomplete: true,
    incompleteReasons: incompleteReasons.filter(
      (reason) => !reason.toLowerCase().includes("photography"),
    ),
    seoTitle: `${draft.title} | Sunny Bunny Toy Co.`,
    seoDescription: draft.shortDescription,
    playerCount: draft.playerCount ?? null,
    playTimeMinutes: draft.playTimeMinutes ?? null,
    readingRequired: draft.readingRequired ?? false,
    indoorOutdoor: draft.indoorOutdoor ?? "indoor",
    keyDetail: draft.keyDetail,
    heightDisplay: draft.heightDisplay ?? null,
  };
}

