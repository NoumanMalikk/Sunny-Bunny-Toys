export const products: Product[] = drafts.map(buildProduct);

export function getAllProducts(): Product[] {
  return products;
}

export function getActiveProducts(): Product[] {
  return products.filter((p) => p.active);
}

export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

export function getProductById(id: string): Product | undefined {
  return products.find((p) => p.id === id);
}

export function getProductsByCategory(category: ProductCategory): Product[] {
  return products.filter((p) => p.active && p.category === category);
}

export function getProductsByCollection(collection: string): Product[] {
  return products.filter((p) => p.active && p.collections.includes(collection));
}

export function getFeaturedProducts(limit = 6): Product[] {
  return products.filter((p) => p.active && p.featured).slice(0, limit);
}

export function getNewArrivals(limit = 8): Product[] {
  return products.filter((p) => p.active && p.newArrival).slice(0, limit);
}

export function getRelatedProducts(product: Product, limit = 4): Product[] {
  const related = product.relatedProductIds
    .map((id) => getProductById(id))
    .filter((p): p is Product => Boolean(p && p.active));
  if (related.length >= limit) return related.slice(0, limit);
  const fillers = products.filter(
    (p) => p.active && p.id !== product.id && p.category === product.category && !related.some((r) => r.id === p.id),
  );
  return [...related, ...fillers].slice(0, limit);
}
